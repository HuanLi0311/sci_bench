"""Refresh model provenance indexes from real per-task attempt inventories."""
import json
from pathlib import Path

from record_baselines import ROOT


def local(value):
    path = Path(value)
    if path.is_absolute():
        return path
    return ROOT.parents[1] / path if value.startswith("tasks/") else ROOT / path


if __name__ == "__main__":
    rows = []
    machine = []
    for task in sorted(ROOT.iterdir()):
        source = task / "authoring/model-attempts.json"
        if not source.exists():
            continue
        data = json.loads(source.read_text())
        if not data["attempts"]:
            rows.append(f"| {task.name} | unmeasured | no actual task attempt recorded | — | — | [inventory]({task.name}/authoring/model-attempts.json) |")
        for attempt in data["attempts"]:
            machine.append({"task": task.name, **attempt})
            path = local(attempt["path"]).relative_to(ROOT).as_posix()
            effective = attempt.get("effective_config", {})
            reported = attempt.get("reported_agent") or {}
            agent = effective.get("agent") or effective.get("agent_type") or attempt.get("agent_config", {}).get("name") or attempt.get("agent", "not recorded")
            version = effective.get("cli_version") or effective.get("CLI") or reported.get("version", "version not recorded")
            effort = effective.get("reasoning_effort", "effort not recorded")
            model = attempt.get("model_identifier", "not recorded")
            execution = attempt.get("outcome", attempt.get("status", "not recorded"))
            posthoc = attempt.get("posthoc_current_artifact_evaluation", {})
            reward = posthoc.get("reward", attempt.get("reward"))
            grading = posthoc.get("run", attempt.get("grading_run"))
            score = "not graded" if reward is None else str(reward)
            if grading:
                target = local(grading).relative_to(ROOT).as_posix()
                score += f" ([grade]({target}/run.json))"
            raw_codex = attempt.get("trajectory_format", "").startswith("Codex raw JSONL")
            if raw_codex or attempt.get("trajectory_present"):
                steps = f"{attempt.get('agent_steps')} agent items / {attempt.get('tool_calls')} tool requests" if raw_codex else f"{attempt.get('agent_steps')} ATIF agent steps / {attempt.get('tool_calls')} requests"
            else:
                steps = "no inference transcript recovered"
            evidence = f"[config]({path}/config.json), [log]({path}/trial.log), [inventory]({task.name}/authoring/model-attempts.json)"
            if (ROOT / path / "observations/README.md").exists():
                evidence += f", [images]({path}/observations/README.md)"
            rows.append(f"| {task.name} / {attempt['id']} | {model}; {agent} / {version} / {effort} | {execution} | {score} | {steps} | {evidence} |")
    text = """# Model attempts and complete trace index

Execution status, artifact score and GUI/CUA compliance are separate. Infrastructure/setup failures and API-rate-limit or quota terminations are not counted as model capability failures. Terminal baselines are not GUI/CUA compliance trials; no pass-rate estimate is inferred from this inventory. Rows are generated by `tools/summarize_models.py` from actual per-task inventories. Running and unmeasured entries are explicit.

| Task / attempt | Recorded model and Agent | Execution result | Artifact score | Recorded steps | Raw evidence |
|---|---|---|---|---|---|
""" + "\n".join(rows) + """

ATIF counts include steps whose source is agent; requests are the sum of tool_calls lengths. The recovered complete historical crate attempt has 73 total ATIF steps, 67 agent steps and 66 requests. Its unchanged submission fails the current verifier; failed historical setup trials have no invented inference trace.

For raw Codex JSONL, agent items are response_item events containing assistant messages or function_call/custom_tool_call requests; tool requests count the two call types only. Excludes user/system messages, reasoning-only items, results, initialization, verifier actions and duplicate CLI representations. All sessions are included. These counts are requests, not successful shell commands or GUI clicks. New trial independent-step-check.json files separately verify counts and duplicate call IDs.

The first booth runtime failure has 21 agent items / 18 requests: 11 exec requests failed because the companion code-mode host was absent; seven scheduling/wait requests remained available. The corrected-runtime booth attempt has 88 agent items / 73 requests and terminated on API 429. Its unchanged artifacts pass the corrected 22-check verifier, while CLI exit 1 and gui_compliant=false remain recorded. The independent runtime smoke is diagnostic, not a task attempt or NOP.

New task trials preserve the exact prompt/instruction, effective non-sensitive Agent configuration, binary versions/hashes, material hashes and stored input bytes, raw CLI events and sessions, original submissions and separate grading records. Image observations, when present, are extracted byte-for-byte from raw data URIs with event locations and SHA-256. Private authentication/configuration bodies are excluded.

Model identifiers are exact requested/reported identifiers, such as gpt-6.1-sol. No immutable provider weight snapshot was recorded; unknown historical fields remain unknown. A task that has not actually run is not assigned a fabricated model result.
"""
    (ROOT / "MODEL_ATTEMPTS.md").write_text(text)
    (ROOT / "model-attempt-index.json").write_text(json.dumps(machine, indent=2) + "\n")
    print(f"Indexed {len(machine)} actual task attempts")
