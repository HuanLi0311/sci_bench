"""Build a reviewable index from captured run records, without inventing results."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    rows = []
    for task in sorted(ROOT.iterdir()):
        if not (task / "task.toml").exists():
            continue
        for path in sorted((task / "authoring/runs").glob("*/run.json")):
            meta = json.loads(path.read_text(encoding="utf-8"))
            metrics_path = path.parent / "verifier/metrics.json"
            metrics, error = {}, None
            try:
                metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                error = str(exc)
            details = " ".join(str(c.get("detail", "")) for c in metrics.get("checks", []))
            if not meta.get("finished_at"):
                classification = "unfinished"
            elif meta.get("agent_exit_code") not in (None, 0):
                classification = "agent-execution-error"
            elif "timed out" in details or meta.get("verifier_exit_code") == 124:
                classification = "verifier-timeout"
            elif error or meta.get("error"):
                classification = "verifier-execution-error"
            else:
                classification = "graded"
            rows.append({
                "task": task.name, "run": path.parent.relative_to(ROOT).as_posix(),
                "kind": meta["kind"], "label": meta["label"],
                "finished_at": meta.get("finished_at"), "reward": meta.get("reward"),
                "agent_exit_code": meta.get("agent_exit_code"),
                "verifier_exit_code": meta.get("verifier_exit_code"),
                "failed_checks": [c["id"] for c in metrics.get("checks", []) if not c["pass"]],
                "metrics_error": error, "run_error": meta.get("error"),
                "classification": classification,
                "grader_source": meta["grader_source"],
            })
    (ROOT / "run-index.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
    lines = ["| Task | Run | Reward | Failed checks / state |", "|---|---|---|---|"]
    for row in rows:
        state = ", ".join(row["failed_checks"]) or ("all checks pass" if row["reward"] == 1 else "pending/error")
        if row["metrics_error"]:
            state = "invalid/missing metrics (see raw stderr)"
        if row["classification"] != "graded":
            state = row["classification"] + ": " + state
        lines.append(f"| {row['task']} | [{row['label']} / {row['kind']}]({row['run']}/run.json) | {row['reward']} | {state} |")
    (ROOT / "RUNS.md").write_text(
        "# Captured execution records\n\nGenerated by `python3 tools/summarize_runs.py`. "
        "Only rows labelled `final` are the frozen verifier validation. "
        "Earlier runs include development failures and different source snapshots; inspect `grader_source` hashes. "
        "A reward of 0 after an agent setup or verifier error is not a model-solving failure.\n\n"
        + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Indexed {len(rows)} actual captured runs")


if __name__ == "__main__":
    main()
