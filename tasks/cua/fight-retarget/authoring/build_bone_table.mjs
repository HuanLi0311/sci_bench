import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const root=new URL('../',import.meta.url);
const rows=JSON.parse(await fs.readFile(new URL('environment/materials/bone_mapping.json',root),'utf8'));
const wb=Workbook.create(),sheet=wb.worksheets.add('Bone mapping');
sheet.showGridLines=false;
sheet.getRange('A1:J1').values=[['Character','Bone','Parent','Length (m)','Head X (m)','Head Y (m)','Head Z (m)','Tail X (m)','Tail Y (m)','Tail Z (m)']];
sheet.getRange(`A2:J${rows.length+1}`).values=rows.map(r=>[r.character,r.bone,r.parent,r.length,...r.head,...r.tail]);
sheet.getRange(`A1:J${rows.length+1}`).format.font={name:'Arial',size:10};
sheet.getRange('A1:J1').format={fill:'#244363',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},rowHeight:26};
sheet.getRange('A1:C45').format.columnWidth=20;
sheet.getRange('D1:J45').format.columnWidth=14;
sheet.getRange('D2:J45').setNumberFormat('0.000000');
sheet.getRange('A2:J45').format.rowHeight=21;
sheet.freezePanes.freezeRows(1);
wb.recalculate();
const inspection=await wb.inspect({kind:'region',sheetId:sheet.name,range:'A1:J4',maxChars:2000});
console.log(inspection.ndjson);
const render=await wb.render({sheetName:sheet.name,range:'A1:J14',scale:1.5,format:'png'});
await fs.writeFile(new URL('./bone-mapping-preview.png',import.meta.url),new Uint8Array(await render.arrayBuffer()));
const xlsx=await SpreadsheetFile.exportXlsx(wb);
await xlsx.save(new URL('environment/materials/bone_mapping.xlsx',root).pathname.replace(/^\/(\w:)/,'$1'));
